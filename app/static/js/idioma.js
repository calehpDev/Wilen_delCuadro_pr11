function setLanguage(lang) {
    const currentLang = translations[lang] ? lang : "es";

    localStorage.setItem("app_lang", currentLang);

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.getAttribute("data-i18n");
        if (translations[currentLang][key] !== undefined) {
            element.innerHTML = translations[currentLang][key];
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        const key = element.getAttribute("data-i18n-placeholder");
        if (translations[currentLang][key] !== undefined) {
            element.setAttribute("placeholder", translations[currentLang][key]);
        }
    });

    const langBtns = [
        document.getElementById("lang-toggle"),
        document.getElementById("lang-toggle-mobile")
    ];

    langBtns.forEach((btn) => {
        if (btn) {
            btn.textContent = currentLang === "es" ? "🇺🇸 EN" : "🇵🇪 ES";
        }
    });
}

document.addEventListener("DOMContentLoaded", () => {
    const savedLang = localStorage.getItem("app_lang") || "es";
    setLanguage(savedLang);

    const langToggleBtn = document.getElementById("lang-toggle");
    const langToggleMobileBtn = document.getElementById("lang-toggle-mobile");

    const toggleLanguageHandler = () => {
        const activeLang = localStorage.getItem("app_lang") || "es";
        setLanguage(activeLang === "es" ? "en" : "es");
    };

    if (langToggleBtn) {
        langToggleBtn.addEventListener("click", toggleLanguageHandler);
    }

    if (langToggleMobileBtn) {
        langToggleMobileBtn.addEventListener("click", toggleLanguageHandler);
    }
});